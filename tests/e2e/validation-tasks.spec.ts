async function prepare(page: Page) {
  await page.route('**/health', route => route.fulfill({ json: { providerConfigured: false } }))
  await page.goto('/')
  await openAdvanced(page, '工作区设置')
  await openAdvanced(page, '仅替换演示评论')
  await openAdvanced(page, '字段映射模板')
  const products = 'productId,title,market,currency,price,capturedAt\nSKU,Sample charger,US,USD,30,2026-10-06'
  const reviews = 'reviewId,productId,locale,rating,body,reviewedAt\nR1,SKU,en-US,2,charger gets hot,2026-10-06'
  for (const [label, csv] of [['商品 CSV', products], ['评论 CSV', reviews]]) await page.getByLabel(label, { exact: true }).setInputFiles({ name: `${label}.csv`, mimeType: 'text/csv', buffer: Buffer.from(csv) })
  await page.getByRole('button', { name: '读取字段', exact: true }).click()
  await page.getByLabel('products-productId').waitFor()
  await page.getByRole('button', { name: '校验并预览' }).click()
  await page.getByRole('checkbox', { name: /我有权使用这些数据/ }).check()
  await page.getByRole('button', { name: '确认导入工作区' }).click()
  await page.getByRole('button', { name: /决策报告/ }).click()
  await openAdvanced(page, '比较两个历史版本')
  await analyzeAndOpenReport(page)
  await expect(page.getByText('分析存档已保存到本机')).toBeVisible()
  await page.getByRole('button', { name: '查看历史报告' }).click()
  await openAdvanced(page, '评论语义人工复核')
  await openAdvanced(page, '验证任务（高级）')
  await openAdvanced(page, '已保存概念图')
  await expect(page.getByRole('button', { name: '创建并保存验证任务' })).toBeEnabled()
}

async function fillTask(page: Page, title = '散热对照验证') {
  await page.getByLabel('验证任务标题').fill(title)
  await page.getByLabel('任务设计假设').fill('散热材料变更可能改善体验，尚未验证')
  await page.getByLabel('任务待验证指标').fill('记录双方温升与使用体验；门槛由用户定义')
  await page.getByLabel('任务验证方法', { exact: true }).selectOption('prototype')
  await page.getByLabel('任务验证步骤').fill('相同环境和负载比较两种样机，记录全部结果')
}

async function download(page: Page, name: string | RegExp) {
  const event = page.waitForEvent('download')
  await page.getByRole('button', { name }).click()
  return readFile((await (await event).path())!, 'utf8')
}

