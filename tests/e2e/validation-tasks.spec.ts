test('failed task save remains unsaved, blocks incomplete export and can be backed up and retried', async ({ page }) => {
  await prepare(page)
  await fillTask(page)
  await page.evaluate(() => {
    const original = IDBObjectStore.prototype.add
    Reflect.set(window, 'restoreTaskAdd', () => { IDBObjectStore.prototype.add = original })
    IDBObjectStore.prototype.add = function (...args) {
      if (this.name === 'validationTasks') throw new DOMException('Quota full', 'QuotaExceededError')
      return original.apply(this, args)
    }
  })
  await page.getByRole('button', { name: '创建并保存验证任务' }).click()
  const panel = page.getByRole('region', { name: '改良验证任务' })
  await expect(panel.getByText(/任务未保存/)).toBeVisible()
  await expect(panel.getByRole('article')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '导出证据 JSON' })).toBeDisabled()
  const failed = JSON.parse(await download(page, '下载未保存任务备份'))
  expect(failed.saved).toBe(false)
  expect(failed.record.plan.title).toBe('散热对照验证')
  expect(failed.previousFiles).toEqual([])
  await page.evaluate(() => Reflect.get(window, 'restoreTaskAdd')())
  await page.getByRole('button', { name: '重试保存任务' }).click()
  await expect(panel.getByRole('article')).toHaveCount(1)
  await expect(page.getByRole('button', { name: '导出证据 JSON' })).toBeEnabled()
})
